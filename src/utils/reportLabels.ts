export function operatingSignalKeys(): string[] { return [...canonical.keys()]; }

export function readableOperatingSignal(section: OperatingSection, value: string, language: Language): string {
  if (value === 'Balanced' || value === 'Balanced Explorer') return t(language, 'reportBalancedSignal');
  const key = `${section}.${value}`;
  if (!canonical.has(key)) return t(language, 'reportUnknownSignal');
  if (language === 'en') return canonical.get(key)!;
  return translations[language][key] ?? t(language, 'reportUnknownSignal');
}

/** The engine's topOperating field has no section field; only unique known IDs may be resolved. */
export function readableTopOperating(value: string, language: Language): string {
  if (value === 'Balanced' || value === 'Balanced Explorer') return t(language, 'reportBalancedSignal');
  const matches = OPERATING_SECTIONS.filter(section => canonical.has(`${section}.${value}`));
  return matches.length === 1 ? readableOperatingSignal(matches[0], value, language) : t(language, 'reportUnknownSignal');
}

export function operatingTranslations(language: Exclude<Language, 'en'>): Readonly<Record<string, string>> {
  return translations[language];
}

